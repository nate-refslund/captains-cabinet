OLD_SHA = "a" * 40
NEW_SHA = "b" * 40

#: The bytes every fixture bundle ships, keyed by repo-relative path. This is
#: the "shipped content" half of an install — the half an update may replace.
BASE_SHIPPED = {
    "cabinet/scripts/hello.sh": "echo hello v1\n",
    "cabinet/scripts/lib/helper.sh": "helper v1\n",
    "cabinet/docs/readme.md": "readme v1\n",
    "framework-note.txt": "note v1\n",
}


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def make_install(tmp_path: Path, *, source_commit: str = OLD_SHA) -> Path:
    """A fixture install: the real updater, the real boundary, real operator data."""

    root = tmp_path / "install"
    (root / "cabinet" / "scripts" / "lib").mkdir(parents=True)
    (root / "cabinet" / "config").mkdir(parents=True)

    shutil.copy2(_UPDATER, root / "cabinet" / "scripts" / "cabinet-update.sh")
    shutil.copy2(_BUNDLE_PY, root / "cabinet" / "scripts" / "lib" / "update_bundle.py")
    # The REAL boundary script — the locked-set parse is only worth anything
    # against the bytes it will actually meet.
    shutil.copy2(_LOCK_SH, root / "cabinet" / "scripts" / "germline-lock.sh")
    shutil.copy2(_PROVISION_SH, root / "cabinet" / "scripts" / "runtime-provision.sh")

    # The preserve set, generated by the same code path the export uses.
    _write(
        root / update_bundle.PRESERVE_SET_REL,
        update_bundle.preserve_set_document(_EXPORT_MANIFEST),
    )

    for rel, text in BASE_SHIPPED.items():
        _write(root / rel, text)

    # Operator data: never written, never deleted, never reported as content.
    _write(root / "instance/config/outcomes.yml", "outcomes:\n  - id: mine\n")
    _write(
        root / "shared/interfaces/captain-vetoes.yml",
        "version: 1\nnext_id: 2\nvetoes:\n  - id: 1\n    what: my own veto\n",
    )

    _write(
        root / "egg-manifest.json",
        json.dumps({"source_commit": source_commit, "cut_at": "2026-09-01T00:00:00Z"},
                   indent=2) + "\n",
    )

    # The real emitter, so the new event types are validated by the real
    # VALID_EVENT_TYPES rather than by a stub that would accept anything.
    os.symlink(_REPO_ROOT / "framework", root / "framework")
    return root


def make_bundle(
    tmp_path: Path,
    install_root: Path,
    sha: str,
    *,
    shipped: dict[str, str] | None = None,
    extra: dict[str, str] | None = None,
    built_at: str | None = None,
    changelog: list[str] | None = None,
    corrupt: bool = False,
    empty: bool = False,
) -> Path:
    """Cut a bundle into the install's inbox, the way `egg-export.sh --bundle` does."""

    tree = tmp_path / f"bundle-{sha[:12]}"
    if tree.exists():
        shutil.rmtree(tree)
    tree.mkdir(parents=True)

    if not empty:
        content = dict(BASE_SHIPPED if shipped is None else shipped)
        content.update(extra or {})
        for rel, text in content.items():
            _write(tree / rel, text)
        # A bundle is a cut of the same tree, so it carries the boundary script
        # and the generated preserve set exactly as the install has them.
        shutil.copy2(_LOCK_SH, tree / "cabinet/scripts/germline-lock.sh")
        _write(
            tree / update_bundle.PRESERVE_SET_REL,
            update_bundle.preserve_set_document(_EXPORT_MANIFEST),
        )
        shutil.copy2(_UPDATER, tree / "cabinet/scripts/cabinet-update.sh")
        shutil.copy2(_BUNDLE_PY, tree / "cabinet/scripts/lib/update_bundle.py")

    inbox = install_root / ".updates" / "inbox"
    inbox.mkdir(parents=True, exist_ok=True)
    manifest_path = inbox / f"{sha}.manifest.json"
    tar_path = inbox / f"{sha}.tar.gz"

    changelog_file = tmp_path / f"changelog-{sha[:12]}.txt"
    changelog_file.write_text("\n".join(changelog or ["a change"]) + "\n", encoding="utf-8")

    subprocess.run(
        [_PY, str(_BUNDLE_PY), "manifest", "--tree", str(tree), "--source-sha", sha,
         "--built-at", built_at or "2026-09-07T00:00:00Z",
         "--changelog-file", str(changelog_file), "--out", str(manifest_path)],
        check=True, capture_output=True, text=True,
    )
    with tarfile.open(tar_path, "w:gz") as tar:
        for child in sorted(tree.iterdir()):
            tar.add(child, arcname=child.name)
    if corrupt:
        # One shipped file's bytes no longer match its manifest digest.
        with tarfile.open(tar_path, "w:gz") as tar:
            (tree / "cabinet/scripts/hello.sh").write_text("tampered\n", encoding="utf-8")
            for child in sorted(tree.iterdir()):
                tar.add(child, arcname=child.name)
    return tree


def run_updater(
    install_root: Path,
    *args: str,
    env_extra: dict[str, str] | None = None,
    script: Path | None = None,
    timeout: int = _RUN_TIMEOUT,
) -> subprocess.CompletedProcess:
    env = dict(os.environ)
    env.update({
        "CABINET_ROOT": str(install_root),
        "CABINET_EVENT_LOG_DIR": str(install_root / ".events"),
        "PYTHONDONTWRITEBYTECODE": "1",
        # The gate's two non-dashboard legs, pointed at commands a fixture
        # install can actually run. `--skip-restart` makes the dashboard leg
        # THIN; the defaults are pinned by their own test below.
        "CABINET_UPDATE_RECEIPTS_CMD": "true",
        "CABINET_UPDATE_PREFLIGHT_CMD": "true",
        "CABINET_UPDATE_SKIP_DOCTOR": "1",
    })
    env.update(env_extra or {})
    target = script or (install_root / "cabinet" / "scripts" / "cabinet-update.sh")
    return subprocess.run(
        ["bash", str(target), *args],
        cwd=str(install_root), capture_output=True, text=True, timeout=timeout, env=env,
    )


def events(install_root: Path) -> list[dict]:
    out: list[dict] = []
    log_dir = install_root / ".events"
    if not log_dir.is_dir():
        return out
    for path in sorted(log_dir.glob("events-*.jsonl")):
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line:
                try:
                    out.append(json.loads(line))
                except ValueError:
                    pass
    return out


def event_types(install_root: Path) -> list[str]:
    return [e.get("event_type") or e.get("type") for e in events(install_root)]


def state(install_root: Path) -> dict:
    path = install_root / ".updates" / "state.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}


def installed_sha(install_root: Path) -> str:
    return json.loads((install_root / "egg-manifest.json").read_text())["source_commit"]


