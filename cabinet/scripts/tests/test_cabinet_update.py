def test_apply_updates_code_and_preserves_instance(tmp_path):
    """A §5.1 / B §5.1: shipped code moves; the operator's own files do not."""
    root = make_install(tmp_path)
    make_bundle(tmp_path, root, NEW_SHA, extra={"cabinet/scripts/hello.sh": "echo hello v2\n"})

    outcomes_before = (root / "instance/config/outcomes.yml").read_bytes()
    vetoes_before = (root / "shared/interfaces/captain-vetoes.yml").read_bytes()

    result = run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart")
    assert result.returncode == 0, result.stderr

    assert (root / "cabinet/scripts/hello.sh").read_text() == "echo hello v2\n"
    assert installed_sha(root) == NEW_SHA
    assert (root / "instance/config/outcomes.yml").read_bytes() == outcomes_before
    assert (root / "shared/interfaces/captain-vetoes.yml").read_bytes() == vetoes_before
    assert "cabinet_update_applied" in event_types(root)
    assert state(root)["phase"] == "applied"


def test_a_non_empty_veto_row_survives_an_apply(tmp_path):
    """A5.2: the live veto ledger is the operator's, even when a bundle ships one.

    The export ships this file HEADER-ONLY (`vetoes: []`), so a bundle always
    carries a copy — and an update that took the shipped copy would silently
    erase every veto the Captain had recorded. This is the arm that says the
    preserve set is doing real work rather than covering paths no bundle
    contains."""
    root = make_install(tmp_path)
    make_bundle(
        tmp_path, root, NEW_SHA,
        extra={"shared/interfaces/captain-vetoes.yml": "version: 1\nnext_id: 1\nvetoes: []\n"},
    )
    before = (root / "shared/interfaces/captain-vetoes.yml").read_text()
    assert "my own veto" in before

    result = run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart")
    assert result.returncode == 0, result.stderr
    assert (root / "shared/interfaces/captain-vetoes.yml").read_text() == before


def test_apply_keeps_preserve_set_and_reports_the_skip(tmp_path):
    """A5.2: a bundle that CONTAINS a preserved path ⇒ skipped AND reported.

    Built on a bundle that ships one on purpose: a preserve test on a bundle
    with no preserved path in it passes against code that has no preserve set
    at all."""
    root = make_install(tmp_path)
    make_bundle(
        tmp_path, root, NEW_SHA,
        extra={
            "instance/config/outcomes.yml": "outcomes: []\n",
            "shared/interfaces/captain-vetoes.yml": "vetoes: []\n",
            "cabinet/scripts/hello.sh": "echo hello v2\n",
        },
    )
    result = run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart")
    assert result.returncode == 0, result.stderr

    assert (root / "instance/config/outcomes.yml").read_text() == "outcomes:\n  - id: mine\n"
    skipped = state(root)["skipped_preserved"]
    assert "instance/config/outcomes.yml" in skipped
    assert "shared/interfaces/captain-vetoes.yml" in skipped
    # Reported, not silently dropped — on the record and on the operator's screen.
    applied = [e for e in events(root) if (e.get("event_type") or e.get("type")) == "cabinet_update_applied"]
    assert applied and "instance/config/outcomes.yml" in applied[-1]["payload"]["skipped_preserved"]
    assert "kept your own data" in result.stderr


def test_same_sha_is_a_noop_with_no_snapshot(tmp_path):
    """A §5.3 / B §5.1: the installed commit ⇒ exit 0, nothing written."""
    root = make_install(tmp_path, source_commit=NEW_SHA)
    make_bundle(tmp_path, root, NEW_SHA)
    result = run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart")
    assert result.returncode == 0, result.stderr
    assert not (root / ".updates" / "snapshots").exists() or not list(
        (root / ".updates" / "snapshots").iterdir()
    )
    assert "cabinet_update_applied" not in event_types(root)


def test_identity_is_the_egg_manifest_and_no_version_file_is_written(tmp_path):
    """A5.3: `.cabinet-version` is cut; egg-manifest.json carries the identity."""
    root = make_install(tmp_path)
    make_bundle(tmp_path, root, NEW_SHA, extra={"cabinet/scripts/hello.sh": "v2\n"})
    run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart")

    doc = json.loads((root / "egg-manifest.json").read_text())
    assert doc["source_commit"] == NEW_SHA
    assert doc["applied_at"]
    assert doc["applied_from"] == OLD_SHA
    assert not list(root.rglob(".cabinet-version"))
    # And no CODE line names one — both files mention it in a comment saying
    # exactly why a second identity file is not written, which is the sentence
    # a later reader needs and not a use.
    for path in (_UPDATER, _BUNDLE_PY):
        code = [line for line in path.read_text().splitlines()
                if ".cabinet-version" in line and not line.lstrip().startswith(("#", '"""'))]
        assert not code, (path.name, code)


