def test_absent_and_empty_bundles_refuse(tmp_path):
    """B §5.7 degenerate end: absent, empty and unreadable are refusals."""
    root = make_install(tmp_path)
    missing = run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart")
    assert missing.returncode == 3, missing.stderr

