def _launch_detached_apply(root: Path, sha: str, extra_env: dict[str, str]) -> subprocess.Popen:
    env = dict(os.environ)
    env.update({
        "CABINET_ROOT": str(root),
        "CABINET_EVENT_LOG_DIR": str(root / ".events"),
        "PYTHONDONTWRITEBYTECODE": "1",
        "CABINET_UPDATE_TEST_RECEIPTS_CMD": "true",
        "CABINET_UPDATE_TEST_PREFLIGHT_CMD": "true",
        "CABINET_UPDATE_SKIP_DOCTOR": "1",
    })
    env.update(extra_env)
    script = extra_env.pop("_SCRIPT", None) or str(root / "cabinet/scripts/cabinet-update.sh")
    # A launcher shell that backgrounds the updater and then sits — the stand-in
    # for the dashboard process the updater is about to restart. `start_new_session`
    # makes the launcher its own process-group leader so the kill below can take
    # the whole group and nothing else.
    return subprocess.Popen(
        ["bash", "-c",
         f'bash {script} apply --bundle {sha} --skip-rebuild --skip-restart >/dev/null 2>&1 &\n'
         f'sleep 120\n'],
        cwd=str(root), env=env, start_new_session=True,
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )


def _wait_for(predicate, seconds: float = 60.0) -> bool:
    deadline = time.time() + seconds
    while time.time() < deadline:
        if predicate():
            return True
        time.sleep(0.25)
    return predicate()


def test_updater_survives_the_death_of_the_process_that_spawned_it(tmp_path):
    """A5.8: the updater re-execs under a new session before its first write.

    It restarts the process that spawned it, so a signal aimed at that
    process's GROUP must not reach it. The kill below is a group kill, which is
    what a terminal hangup and a supervised job restart both are."""
    root = make_install(tmp_path)
    make_bundle(tmp_path, root, NEW_SHA, extra={"cabinet/scripts/hello.sh": "echo hello v2\n"})

    launcher = _launch_detached_apply(root, NEW_SHA, {"CABINET_UPDATE_TEST_HOLD_SECONDS": "5"})
    try:
        assert _wait_for(lambda: (root / ".updates" / "run" / "cabinet-update.sh").is_file(), 30), \
            "the updater never re-exec'd into .updates/run/"
        os.killpg(os.getpgid(launcher.pid), signal.SIGKILL)
        assert _wait_for(lambda: state(root).get("phase") == "applied", 90), state(root)
        assert (root / "cabinet/scripts/hello.sh").read_text() == "echo hello v2\n"
    finally:
        try:
            os.killpg(os.getpgid(launcher.pid), signal.SIGKILL)
        except (ProcessLookupError, PermissionError):
            pass
        launcher.wait(timeout=10)


