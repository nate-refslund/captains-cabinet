def test_refuses_locked_path_whole_bundle(tmp_path):
    """A §5.1 / B §5.3: any differing locked path ⇒ exit 3, nothing written."""
    root = make_install(tmp_path)
    tree = make_bundle(
        tmp_path, root, NEW_SHA,
        extra={"cabinet/scripts/hello.sh": "echo hello v2\n"},
    )
    # A locked FILE, changed by the bundle.
    (tree / "cabinet/scripts/germline-lock.sh").write_text(
        _LOCK_SH.read_text() + "\n# widened\n", encoding="utf-8"
    )
    make_bundle_refresh(tmp_path, root, NEW_SHA, tree)

    before = (root / "cabinet/scripts/hello.sh").read_text()
    result = run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart")
    assert result.returncode == 3, (result.returncode, result.stderr)
    # WHOLE bundle: the unrelated, perfectly applicable file did not move.
    assert (root / "cabinet/scripts/hello.sh").read_text() == before
    assert installed_sha(root) == OLD_SHA
    assert "cabinet_update_refused" in event_types(root)
    assert "constitutional set" in result.stderr
    refused = [e for e in events(root)
               if (e.get("event_type") or e.get("type")) == "cabinet_update_refused"][-1]
    assert "cabinet/scripts/germline-lock.sh" in refused["payload"]["locked_paths"]


def make_bundle_refresh(tmp_path: Path, install_root: Path, sha: str, tree: Path) -> None:
    """Re-cut manifest + tarball after a test mutated a bundle tree in place."""
    inbox = install_root / ".updates" / "inbox"
    changelog_file = tmp_path / f"changelog-refresh-{sha[:12]}.txt"
    changelog_file.write_text("a change\n", encoding="utf-8")
    subprocess.run(
        [_PY, str(_BUNDLE_PY), "manifest", "--tree", str(tree), "--source-sha", sha,
         "--built-at", "2026-09-07T00:00:00Z", "--changelog-file", str(changelog_file),
         "--out", str(inbox / f"{sha}.manifest.json")],
        check=True, capture_output=True, text=True,
    )
    with tarfile.open(inbox / f"{sha}.tar.gz", "w:gz") as tar:
        for child in sorted(tree.iterdir()):
            tar.add(child, arcname=child.name)


def test_refuses_a_locked_DIRS_prefix_not_only_an_exact_file(tmp_path):
    """A5.4: DIRS entries match by PREFIX — the lock is applied with `chflags -R`.

    An exact-match parse would let every file under `cabinet/scripts/hooks/`
    through while reporting the boundary as enforced: a green hole, which is
    strictly worse than an open one."""
    root = make_install(tmp_path)
    _write(root / "cabinet/scripts/hooks/session-hook.py", "old hook\n")
    tree = make_bundle(
        tmp_path, root, NEW_SHA,
        extra={"cabinet/scripts/hooks/session-hook.py": "NEW HOOK\n"},
    )
    make_bundle_refresh(tmp_path, root, NEW_SHA, tree)

    result = run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart")
    assert result.returncode == 3, (result.returncode, result.stderr)
    assert (root / "cabinet/scripts/hooks/session-hook.py").read_text() == "old hook\n"
    refused = [e for e in events(root)
               if (e.get("event_type") or e.get("type")) == "cabinet_update_refused"][-1]
    assert "cabinet/scripts/hooks/session-hook.py" in refused["payload"]["locked_paths"]


def test_a_locked_check_stripped_from_the_script_lets_the_bundle_through(tmp_path):
    """The INVERTED arm for the refusal above.

    Both refusal arms are red on master only because the script does not exist
    yet, which proves nothing about whether the check is wired. This one runs a
    MUTATED copy with the locked branch removed and asserts the bundle lands —
    so the two arms above are known to fail when the property is absent."""
    root = make_install(tmp_path)
    tree = make_bundle(tmp_path, root, NEW_SHA, extra={"cabinet/scripts/hello.sh": "v2\n"})
    (tree / "cabinet/scripts/germline-lock.sh").write_text(
        _LOCK_SH.read_text() + "\n# widened\n", encoding="utf-8"
    )
    make_bundle_refresh(tmp_path, root, NEW_SHA, tree)

    text = _UPDATER.read_text()
    marker = '  if [ "$locked_hits" != "[]" ]; then'
    assert marker in text, "the locked-hit branch moved; this inverted arm must be re-aimed"
    mutated_text = text.replace(marker, '  if false; then', 1)
    mutated = root / "cabinet" / "scripts" / "mutated-update.sh"
    mutated.write_text(mutated_text, encoding="utf-8")

    result = run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart",
                         script=mutated)
    assert result.returncode == 0, result.stderr
    assert (root / "cabinet/scripts/hello.sh").read_text() == "v2\n"


def test_digest_mismatch_refuses(tmp_path):
    """B §5.4: a bundle whose bytes do not match its own manifest is refused."""
