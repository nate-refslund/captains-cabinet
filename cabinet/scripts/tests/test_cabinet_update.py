"""Sensors for the update path — cabinet-update.sh + lib/update_bundle.py.

WHAT IS UNDER TEST. An installed Cabinet is an unpacked export with no version
control in it. `cabinet-update.sh` is the only thing on such a box that can
take a landed improvement, and every one of its refusals is the whole boundary
there: the installed egg carries no filesystem flags, so the updater's parse of
the INSTALLED `germline-lock.sh` is the only thing standing between a bundle
and the constitutional set.

HOW THESE TESTS ARE BUILT, and why not with mocks. Each one provisions a REAL
fixture install (the real updater, the real helper, the real germline-lock.sh,
a real generated preserve set) and runs the real script end to end. The two
things that are stood in for are named and bounded:

  * the health gate's receipts and persistence legs ride their declared env
    seams, because a fixture install has no dashboard and no repository —
    `test_health_gate_defaults_are_the_contract_legs` pins what those commands
    are when nobody overrides them, so the seam cannot quietly become the
    behaviour;
  * `framework/` is symlinked in from the repo so the REAL emitter validates
    the three new event types. A stub emitter would have proved nothing about
    whether `cabinet_update_refused` is a registered type.

THE DEGENERATE END, checked deliberately. Absence is never a pass here: no
preserve declaration, an unparseable locked set, an empty bundle and a missing
manifest each get their own arm, because each one read as "go ahead" is exactly
the fail-open this path exists to avoid. Several arms carry an INVERTED twin
built from a MUTATED copy of the script (the re-exec stripped, the locked check
stripped) so the arm is proven to fail when the property is absent — a sensor
that passes in both directions is a disabled sensor.

Run: python3.12 -m pytest cabinet/scripts/tests/test_cabinet_update.py -q
"""

