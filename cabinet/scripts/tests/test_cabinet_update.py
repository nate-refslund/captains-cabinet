def test_first_apply_deletes_nothing(tmp_path):
    """A5.1: no applied manifest ⇒ the deletion set is empty, by construction.

    A bundle contains no `instance/` path at all (the export manifest deletes
    29 of them), so a bundle-versus-installed diff would mark the operator's
    entire instance tree for deletion. This arm is the one that would catch
    that rewrite."""
    root = make_install(tmp_path)
    _write(root / "cabinet/scripts/never-shipped-to-me.sh", "local\n")
    make_bundle(tmp_path, root, NEW_SHA, extra={"cabinet/scripts/hello.sh": "v2\n"})

    result = run_updater(root, "apply", "--bundle", NEW_SHA, "--skip-rebuild", "--skip-restart")
    assert result.returncode == 0, result.stderr
    assert state(root)["deleted"] == 0
    assert (root / "cabinet/scripts/never-shipped-to-me.sh").is_file()
    assert (root / "instance/config/outcomes.yml").is_file()
    assert (root / "instance/config").is_dir()


def test_second_apply_deletes_only_what_the_previous_bundle_shipped(tmp_path):
    """A5.1: deletions = previous manifest − new manifest, and nothing else."""
    root = make_install(tmp_path)
    _write(root / "cabinet/scripts/never-shipped-to-me.sh", "local\n")
    make_bundle(tmp_path, root, NEW_SHA,
                extra={"cabinet/scripts/retiring.sh": "goes away later\n"})
